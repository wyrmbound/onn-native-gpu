#!/usr/bin/env python3
"""Generate onn_vkshim_gen.c (one forwarding export per command) and exports.txt from vk.xml.

Exported set = core Vulkan 1.0-1.3 plus the WSI and AHardwareBuffer commands that Android's own
libvulkan.so exports, so NDK-built ports find every symbol they import.
Usage: gen_vkshim.py <vk.xml> <out dir>
"""
import sys, xml.etree.ElementTree as ET

ANDROID_EXTS = ["VK_KHR_surface", "VK_KHR_swapchain", "VK_KHR_android_surface",
                "VK_ANDROID_external_memory_android_hardware_buffer"]
# Hand-written in onn_vkshim.c (they need more than a plain forward).
# Android 15's libvulkan.so also exports this one (an alias of 1.4's vkGetImageSubresourceLayout2).
EXTRA = ["vkGetImageSubresourceLayout2EXT"]
HAND = {"vkGetInstanceProcAddr", "vkGetDeviceProcAddr", "vkCreateInstance", "vkDestroyInstance",
        "vkEnumerateInstanceExtensionProperties", "vkEnumerateDeviceExtensionProperties", "vkCreateDevice"}


def for_vulkan(e):
    api = e.get("api")
    return api is None or "vulkan" in api.split(",")


def text(e):
    """Element text without <comment> children."""
    out = [e.text or ""]
    for c in e:
        if c.tag != "comment":
            out.append(text(c))
        out.append(c.tail or "")
    return "".join(out)


def main(xml_path, out_dir):
    reg = ET.parse(xml_path).getroot()
    cmds, aliases = {}, {}
    for c in reg.findall("commands/command"):
        if not for_vulkan(c):
            continue
        if c.get("alias"):
            aliases[c.get("name")] = c.get("alias")
        else:
            cmds[c.find("proto/name").text] = c

    wanted = []
    def take(block):
        for req in block.findall("require"):
            if for_vulkan(req):
                for c in req.findall("command"):
                    if c.get("name") not in wanted:
                        wanted.append(c.get("name"))
    for f in reg.findall("feature"):
        if for_vulkan(f) and float(f.get("number")) <= 1.3:
            take(f)
    core = list(wanted)
    exts = {e.get("name"): e for e in reg.findall("extensions/extension")}
    for name in ANDROID_EXTS:
        take(exts[name])
    wanted += EXTRA

    out = ["/* GENERATED by gen_vkshim.py from vk.xml: do not edit. Included by onn_vkshim.c. */", ""]
    for name in wanted:
        if name in HAND:
            continue
        c = cmds[aliases.get(name, name)]
        proto = c.find("proto")
        ret = text(proto).rsplit(proto.find("name").text, 1)[0].strip()
        params = [text(p).strip() for p in c.findall("param") if for_vulkan(p)]
        args = ", ".join(p.find("name").text for p in c.findall("param") if for_vulkan(p))
        call = f"f({args});"
        out += [f"static PFN_vkVoidFunction p_{name};",
                f"ONN_EXPORT {ret} VKAPI_CALL {name}({', '.join(params) or 'void'}) {{",
                f"    PFN_{name} f = ONN_RESOLVE({name});",
                f"    {call if ret == 'void' else 'return ' + call}",
                "}", ""]
    out += ["/* Every generated export by name: the ONN_TRACE build hands these out from GIPA/GDPA. */",
            "static const struct { const char *name; PFN_vkVoidFunction f; } onn_gen_exports[] __attribute__((unused)) = {"]
    out += [f'    {{ "{name}", (PFN_vkVoidFunction){name} }},' for name in wanted if name not in HAND]
    out += ["};", ""]
    open(f"{out_dir}/onn_vkshim_gen.c", "w", newline="\n").write("\n".join(out))
    open(f"{out_dir}/exports.txt", "w", newline="\n").write("\n".join(sorted(wanted)) + "\n")
    open(f"{out_dir}/core13.txt", "w", newline="\n").write("\n".join(sorted(core)) + "\n")
    print(f"gen_vkshim: {len(wanted)} exports ({len(core)} core 1.0-1.3, {len(wanted) - len(core)} Android WSI/AHB/extra), "
          f"{len(wanted) - len(HAND)} generated")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
