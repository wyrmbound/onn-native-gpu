#!/usr/bin/env python3
"""Generates jnishim.c from Android's jni.h: a JNIEnv/JavaVM whose every slot is a logging stub.
Usage: python3 gen_jnishim.py <path/to/jni.h> > jnishim.c
Rules: handle creators (FindClass, Get*ID, New*, GetObjectClass, GetSuperclass, AllocObject, PopLocalFrame)
return a non-NULL dummy; other pointer returns are NULL (array element getters: a zeroed scratch buffer);
GetStringUTFChars returns ""; numbers return 0; GetVersion/GetEnv/Attach* succeed with our env."""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()

def members(struct):
    m = re.search(r"struct %s \{(.*?)\n\};" % struct, src, re.S)
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    out = []
    for decl in body.split(";"):
        decl = " ".join(decl.split())
        if not decl: continue
        fm = re.match(r"(.+?)\(\s*\*\s*(\w+)\s*\)\s*\((.*)\)$", decl)
        if fm: out.append(("fn", fm.group(1).strip(), fm.group(2), fm.group(3).strip()))
        else: out.append(("data", decl.split()[-1].lstrip("*")))
    return out

CREATORS = {"FindClass","GetMethodID","GetStaticMethodID","GetFieldID","GetStaticFieldID","GetObjectClass",
            "GetSuperclass","AllocObject","PopLocalFrame"}
def default(ret, name):
    r = ret.replace("const", "").strip()
    if r == "void": return None
    if name == "GetVersion": return "JNI_VERSION_1_6"
    if name in ("GetStringUTFChars",): return '""'
    if name in ("GetStringChars", "GetStringCritical"): return "g_empty_jchars"
    if r.endswith("*"):
        base = r[:-1].strip()
        if "Elements" in name or name == "GetPrimitiveArrayCritical": return "(%s)g_scratch" % r
        return "NULL"
    if name in CREATORS or name.startswith("New"): return "(%s)&g_dummy" % r
    if r in ("jobject","jclass","jstring","jthrowable","jweak","jmethodID","jfieldID") or r.endswith("Array"): return "NULL"
    return "0"

def params(p):
    if p in ("", "void"): return "void", []
    parts, depth, cur = [], 0, ""
    for ch in p:
        if ch == "(": depth += 1
        if ch == ")": depth -= 1
        if ch == "," and depth == 0: parts.append(cur.strip()); cur = ""
        else: cur += ch
    parts.append(cur.strip())
    named, names = [], []
    for i, t in enumerate(parts):
        if t == "...": named.append("..."); continue
        named.append("%s a%d" % (t, i)); names.append("a%d" % i)
    return ", ".join(named), names

env = members("JNINativeInterface")
vm = members("JNIInvokeInterface")
print("/* GENERATED by gen_jnishim.py from jni.h: do not edit, regenerate. */")
print('#include <stdio.h>\n#include <string.h>\n#include "jni.h"\n#include "jnishim.h"\n')
print("static int g_dummy; static jchar g_empty_jchars[1]; static char g_scratch[4096];")
print("static JNIEnv g_env; static JavaVM g_vm;")
print('#define NAMED(...) do { static int left = 200; if (left > 0) { left--; fprintf(stderr, "jnishim: " __VA_ARGS__); fputc(10, stderr); } } while (0)')
print('#define ONCE(n) do { static int seen; if (!seen) { seen = 1; fprintf(stderr, "jnishim: %s" "\\n", n); } } while (0)\n')
# The one question a port's Java side must really answer: "which folder is mine?". Method IDs remember their name,
# and a String-returning call to one of the names below gets the game's data dir (APKRUN_DATA) as a string object
# that GetStringUTFChars understands. Everything else still returns NULL.
print('''#include <stdlib.h>
static struct { char name[64]; } g_meths[128]; static int g_nmeth;
static void *meth(const char *name)
{
    for (int i = 0; i < g_nmeth; i++) if (!strcmp(g_meths[i].name, name ? name : "")) return &g_meths[i];
    if (g_nmeth == 128) return &g_dummy;
    snprintf(g_meths[g_nmeth].name, sizeof g_meths[0].name, "%s", name ? name : "");
    return &g_meths[g_nmeth++];
}
static struct { char text[1024]; } g_dirstr;
static const char *const g_dir_methods[] = { "getDataRootPathFromNative" /* 2Ship */, "romFolder" /* Gen1Recomp */ };
static jobject string_answer(jmethodID m)
{
    const char *p = (const char *)m;
    if (p < g_meths[0].name || p >= g_meths[128].name) return NULL;
    for (size_t i = 0; i < sizeof g_dir_methods / sizeof *g_dir_methods; i++)
        if (!strcmp(p, g_dir_methods[i])) {
            const char *d = getenv("APKRUN_DATA");
            snprintf(g_dirstr.text, sizeof g_dirstr.text, "%s", d ? d : ".");
            fprintf(stderr, "jnishim: %s() -> %s" "\\n", p, g_dirstr.text);
            return (jobject)&g_dirstr;
        }
    return NULL;
}
''')
for kind, *rest in env:
    if kind != "fn": continue
    ret, name, p = rest
    sig, names = params(p)
    body = ""
    if name == "GetJavaVM": body = "*a1 = &g_vm; "
    # which Java class or method the game asked for: without the name a waiting game cannot be diagnosed
    if name == "FindClass": body = 'NAMED("FindClass %s", a1 ? a1 : "?"); '
    if name in ("GetMethodID", "GetStaticMethodID", "GetFieldID", "GetStaticFieldID"):
        body = 'NAMED("%s %%s %%s", a2 ? a2 : "?", a3 ? a3 : "?"); ' % name
    if name in ("GetMethodID", "GetStaticMethodID"): body += "return (jmethodID)meth(a2); "
    if name.startswith(("CallObjectMethod", "CallStaticObjectMethod")): body += "{ jobject s_ = string_answer(a2); if (s_) return s_; } "
    if name == "GetStringUTFChars": body += "if ((void *)a1 == (void *)&g_dirstr) return g_dirstr.text; "
    if name in ("GetStringUTFLength", "GetStringLength"): body += "if ((void *)a1 == (void *)&g_dirstr) return (jsize)strlen(g_dirstr.text); "
    d = default(ret, name)
    print("static %s shim_%s(%s) { ONCE(\"%s\"); %s%s }" % (ret, name, sig, name, body, ("return %s;" % d) if d else ""))
print("\nstatic const struct JNINativeInterface g_table = {")
for kind, *rest in env:
    if kind == "fn": print("    .%s = shim_%s," % (rest[1], rest[1]))
print("};\n")
for kind, *rest in vm:
    if kind != "fn": continue
    ret, name, p = rest
    sig, names = params(p)
    body = ""
    if name in ("AttachCurrentThread", "AttachCurrentThreadAsDaemon"): body = "*a1 = &g_env; "
    if name == "GetEnv": body = "*a1 = &g_env; "
    print("static %s vm_%s(%s) { ONCE(\"%s\"); %sreturn JNI_OK; }" % (ret, name, sig, name, body))
print("\nstatic const struct JNIInvokeInterface g_invoke = {")
for kind, *rest in vm:
    if kind == "fn": print("    .%s = vm_%s," % (rest[1], rest[1]))
print("};\n")
print("static JNIEnv g_env = &g_table; static JavaVM g_vm = &g_invoke;")
print("JNIEnv *jnishim_env(void) { return &g_env; }")
print("JavaVM *jnishim_vm(void) { return &g_vm; }")
print("jobject jnishim_activity(void) { return (jobject)&g_dummy; }")
