#!/bin/bash
# apkinstall: turn any 64-bit SDL APK into a game folder that apkrun can launch on the box. No per-game steps.
#   1. arm64 libs + assets out of the APK      2. entry lib = the one exporting SDL_main
#   3. the APK's own libSDL2.so / libSDL3.so dropped (our SDL replaces it on the box)
#   4. any library a game lib NEEDs that neither the APK nor our runtime has -> a generated stand-in that
#      defines every symbol the game imports from nowhere else (functions returning 0)
#   5. assets/ become the data dir (SDL's internal storage path and cwd), so relative file loads find them
#   6. game.json: id, entry lib, engine
# Usage: apkinstall.sh <game.apk> <out dir>      (then push <out dir> to /data/local/tmp/games/<id>)
set -eu
APK=$1; OUT=$2
T=/opt/ndk-shim/toolchains/llvm/prebuilt/linux-aarch64/bin
RT=${ONN_RUNTIME:-/root/pb/bundle}                                  # the box's bionic runtime (libc, liblog, ...)
DIST=${ONN_DIST:-/root/panvk-kbase-android/dist/android-gl-g610-v10-csf} # our GL + SDL
rm -rf "$OUT"; mkdir -p "$OUT/data"
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
unzip -q -o "$APK" 'lib/arm64-v8a/*' -d "$W" 2>/dev/null || { echo "no arm64 code in this APK"; exit 3; }
unzip -q -o "$APK" 'assets/*' -d "$W" 2>/dev/null || true
cp "$W"/lib/arm64-v8a/*.so "$OUT/"
[ -d "$W/assets" ] && cp -r "$W/assets/." "$OUT/data/"
rm -f "$OUT/libSDL2.so" "$OUT/libSDL3.so"
syms() { "$T/llvm-nm" -D "$@" 2>/dev/null; }
needed() { "$T/llvm-readelf" -d "$1" | sed -n 's/.*Shared library: \[\(.*\)\]/\1/p'; }

ENTRY=""
for so in "$OUT"/*.so; do syms --defined-only "$so" | grep -q ' T SDL_main$' && ENTRY=$(basename "$so"); done
[ -n "$ENTRY" ] || { echo "no SDL_main: not an SDL app (engine not supported yet)"; exit 4; }
ENGINE=sdl2; grep -q 'libSDL3.so' <(for so in "$OUT"/*.so; do needed "$so"; done) && ENGINE=sdl3

# what everything here exports, plus our runtime
have_lib() { [ -e "$OUT/$1" ] || [ -e "$RT/$1" ] || [ -e "$DIST/$1" ] || [ "$1" = libSDL2.so ] || [ "$1" = libSDL3.so ]; }
{ for so in "$OUT"/*.so "$RT"/*.so "$DIST"/*.so*; do syms --defined-only "$so" | awk '{print $3}'; done; } | sed 's/@.*//' | sort -u > "$W/defined"
MISSING=$(for so in "$OUT"/*.so; do needed "$so"; done | sort -u | while read -r l; do have_lib "$l" || echo "$l"; done)
if [ -n "$MISSING" ]; then
  for so in "$OUT"/*.so; do syms --undefined-only "$so" | awk '{print $2}'; done | sed 's/@.*//' | sort -u > "$W/undef"
  comm -23 "$W/undef" "$W/defined" | grep -v -E '^(SDL_|_ITM|__gmon|_Jv_|__cxa_finalize$)' > "$W/stub_syms" || true
  { echo '/* generated by apkinstall: stand-ins for Android libraries our runtime does not have */'
    while read -r s; do echo "long $s(void) { return 0; }"; done < "$W/stub_syms"; } > "$W/stubs.c"
  for l in $MISSING; do
    "$T/aarch64-linux-android29-clang" -shared -w -o "$OUT/$l" -Wl,-soname,"$l" "$W/stubs.c"
  done
  echo "stand-ins: $MISSING ($(wc -l < "$W/stub_syms") symbols)"
fi
ID=$(basename "$APK" .apk | tr 'A-Z' 'a-z' | tr -c 'a-z0-9\n' '-')
printf '{ "id": "%s", "entry": "%s", "engine": "%s" }\n' "$ID" "$ENTRY" "$ENGINE" > "$OUT/game.json"
echo "installed $ID: entry $ENTRY, engine $ENGINE, $(ls "$OUT"/*.so | wc -l) libs, data $(du -sh "$OUT/data" | cut -f1)"
